"""
Example 1: run all six comparison methods and save raw numerical results.

This script performs the optimization/continuation computations only.  All raw
CSV files and the timing summary are written to ``example1_results/``.

After this script finishes, run ``example1_postprocess_final.py`` to construct
the final empirical reference front, compute metrics, and generate figures.

Keep this file in the same directory as:
  common_problem.py
  proposedHomotopy_endpoint_corrected.py
  weightedSum_updated.py
  globalCriterion_updated.py
  lexicographical_updated.py
  epsilonConstraints_updated.py

Optional background file:
  projected_feasible_solution.csv
"""

from contextlib import contextmanager
from pathlib import Path
import os
import shutil
import time

import numpy as np
import pandas as pd

from pymoo.core.problem import Problem
from pymoo.algorithms.moo.nsga2 import NSGA2
from pymoo.optimize import minimize as pymoo_minimize
from pymoo.termination import get_termination
from pymoo.operators.sampling.rnd import FloatRandomSampling

from common_problem import f1, f2, g_leq, h1, h2, diagnostics, XL, XU, SEED
from proposedHomotopy_endpoint_corrected import run_homotopy_analysis
from weightedSum_updated import weightedSumRunner
from globalCriterion_updated import globalCriterionRunner
from lexicographical_updated import lexicographicRunner
from epsilonConstraints_updated import epsilonConstraintRunner


# ============================================================
# Experiment controls
# ============================================================
NSGA_EQ_TOLS = [1e-1, 1e-2, 1e-3, 1e-4]
NSGA_POP_SIZE = 800
NSGA_N_GEN = 800
GLOBAL_P = 2

SCRIPT_DIR = Path(__file__).resolve().parent
RESULTS_DIR = SCRIPT_DIR / "example1_results"
TIMING_FILE = "method_timing_summary.csv"


@contextmanager
def working_directory(path):
    """Temporarily change the working directory."""
    old = Path.cwd()
    os.chdir(path)
    try:
        yield
    finally:
        os.chdir(old)


# ============================================================
# NSGA-II equality-tolerance study
# ============================================================
class FiveVarConstrainedTol(Problem):
    def __init__(self, eq_tol):
        super().__init__(n_var=5, n_obj=2, n_ieq_constr=5, xl=XL, xu=XU)
        self.eq_tol = float(eq_tol)
        self.n_points_evaluated = 0

    def _evaluate(self, X, out, *args, **kwargs):
        self.n_points_evaluated += len(X)
        H1 = h1(X)
        H2 = h2(X)
        t = self.eq_tol
        out["F"] = np.column_stack([f1(X), f2(X)])
        out["G"] = np.column_stack([
            g_leq(X), H1 - t, -H1 - t, H2 - t, -H2 - t
        ])


def run_nsga2(eq_tol, pop_size=NSGA_POP_SIZE, n_gen=NSGA_N_GEN):
    start = time.perf_counter()
    problem = FiveVarConstrainedTol(eq_tol)
    algorithm = NSGA2(
        pop_size=pop_size,
        sampling=FloatRandomSampling(),
        eliminate_duplicates=True,
    )
    res = pymoo_minimize(
        problem,
        algorithm,
        get_termination("n_gen", n_gen),
        seed=SEED,
        verbose=False,
    )

    elapsed = time.perf_counter() - start
    if res.X is None:
        print(f"WARNING: NSGA-II returned no feasible points for eq_tol={eq_tol:g}")
        return pd.DataFrame(), elapsed, problem.n_points_evaluated

    rows = []
    for x in np.atleast_2d(res.X):
        d = diagnostics(x)
        rows.append({
            **{f"x{i+1}": x[i] for i in range(5)},
            "f1": float(f1(x)),
            "f2": float(f2(x)),
            "g": d["g"],
            "h1": d["h1"],
            "h2": d["h2"],
            "max_abs_h": d["max_abs_h"],
            "bound_margin": d["bound_margin"],
            "eq_tol": eq_tol,
        })

    df = pd.DataFrame(rows).sort_values("f1").reset_index(drop=True)
    tag = f"{eq_tol:.0e}".replace("-", "m").replace("+", "p")
    df.to_csv(f"solution_nsga2_eqtol_{tag}.csv", index=False)

    print(
        f"NSGA-II eq_tol={eq_tol:g}: {len(df)} points, "
        f"{problem.n_points_evaluated} evaluations, {elapsed:.2f} s, "
        f"max |h|={df.max_abs_h.max():.3e}"
    )
    return df, elapsed, problem.n_points_evaluated


def timed_call(label, func, *args, **kwargs):
    start = time.perf_counter()
    result = func(*args, **kwargs)
    elapsed = time.perf_counter() - start
    print(f"{label} elapsed time: {elapsed:.2f} s")
    return result, elapsed


# ============================================================
# Main experiment
# ============================================================
def main():
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)

    # The feasible-background file is not generated by the six methods, but if
    # it already exists beside this script, copy it into the results folder so
    # the postprocessor has a single data location.
    background = SCRIPT_DIR / "projected_feasible_solution.csv"
    if background.exists():
        shutil.copy2(background, RESULTS_DIR / background.name)

    timings = []

    # Existing method runners write their CSV files to the current working
    # directory.  Run them from RESULTS_DIR so all raw outputs are collected in
    # one place without modifying the individual method implementations.
    with working_directory(RESULTS_DIR):
        print("\n" + "=" * 72 + "\n1. ENDPOINT-CORRECTED HOMOTOPY\n" + "=" * 72)
        _, elapsed = timed_call("Homotopy", run_homotopy_analysis)
        timings.append(("Homotopy", elapsed, np.nan))

        print("\n" + "=" * 72 + "\n2. WEIGHTED SUM\n" + "=" * 72)
        _, elapsed = timed_call("Weighted Sum", weightedSumRunner)
        timings.append(("Weighted Sum", elapsed, np.nan))

        print("\n" + "=" * 72 + "\n3. GLOBAL CRITERION\n" + "=" * 72)
        _, elapsed = timed_call("Global Criterion", globalCriterionRunner, p=GLOBAL_P)
        timings.append(("Global Criterion", elapsed, np.nan))

        print("\n" + "=" * 72 + "\n4. NSGA-II EQUALITY-TOLERANCE STUDY\n" + "=" * 72)
        for tol in NSGA_EQ_TOLS:
            _, elapsed, neval = run_nsga2(tol)
            timings.append((f"NSGA-II tol={tol:g}", elapsed, neval))

        print("\n" + "=" * 72 + "\n5. LEXICOGRAPHICAL\n" + "=" * 72)
        _, elapsed = timed_call("Lexicographical", lexicographicRunner)
        timings.append(("Lexicographical", elapsed, np.nan))

        print("\n" + "=" * 72 + "\n6. EPSILON-CONSTRAINT\n" + "=" * 72)
        _, elapsed = timed_call("Epsilon-Constraint", epsilonConstraintRunner)
        timings.append(("Epsilon-Constraint", elapsed, np.nan))

        timing_df = pd.DataFrame(
            timings,
            columns=["Method", "seconds", "candidate_evaluations"],
        )
        timing_df.to_csv(TIMING_FILE, index=False)

    print("\n" + "=" * 72)
    print("ALL METHOD RUNS COMPLETED")
    print("=" * 72)
    print(f"Raw data and timing outputs are in:\n  {RESULTS_DIR}")
    print("\nNext run: example1_postprocess_final.py")


if __name__ == "__main__":
    main()
